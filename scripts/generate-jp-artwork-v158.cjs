'use strict';

// Rebuilds the checked-in JP artwork manifest from exact set records. This is a
// maintainer tool, not runtime code: RareWorth never scrapes third-party HTML in
// the user's browser.
const fs=require('node:fs');
const path=require('node:path');

const SETS=[
  {source:'PMCG1',canonical:'BASE',art:6,label:'Base Set'},
  {source:'PMCG2',canonical:'JUNGLE',art:8,label:'Pokémon Jungle'},
  {source:'PMCG3',canonical:'FOSSIL',art:9,label:'The Secret of the Fossil'},
  {source:'neo1',canonical:'NEO GENESIS',art:31,label:'Gold, Silver, to a New World...'},
  {source:'neo2',canonical:'NEO DISCOVERY',art:34,label:'Crossing the Ruins...'},
  {source:'neo3',canonical:'NEO REVELATION',art:40,label:'Awakening Legends'},
  {source:'neo4',canonical:'NEO DESTINY',art:43,label:'Darkness, and to Light...'}
];
const ART='https://www.artofpkm.com';
const TCGDEX_DATA=path.resolve(process.env.TCGDEX_DATA_ROOT||'../tcgdex-data/data-asia');

const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function get(url,kind='text'){
  let last;
  for(let attempt=0;attempt<4;attempt++){
    try{
      const response=await fetch(url,{headers:{'user-agent':'RareWorth artwork manifest verifier/1.0'},signal:AbortSignal.timeout(45000)});
      if(!response.ok)throw new Error(`${response.status} ${response.statusText}`);
      return kind==='json'?response.json():response.text();
    }catch(error){last=error;await sleep(500*(attempt+1));}
  }
  throw new Error(`${url}: ${last?.message||last}`);
}
function decode(value){
  return String(value||'').replace(/&amp;/g,'&').replace(/&#39;|&apos;/g,"'").replace(/&quot;/g,'"').replace(/&eacute;/g,'é').replace(/&nbsp;/g,' ');
}
function key(value){return decode(value).normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/♀/g,'-f').replace(/♂/g,'-m').replace(/[^a-z0-9]+/g,'');}
function speciesKey(value){return key(String(value||'').replace(/^(dark|light|shining)\s+/i,''));}
function parseArtCards(html,set){
  const rows=[];
  const expression=/<a\s+([^>]*data-lightbox-title="[^"]+"[^>]*)>\s*<img[^>]+>/g;
  for(const match of html.matchAll(expression)){
    const attrs=match[1],title=attrs.match(/data-lightbox-title="([^"]+)"/)?.[1];
    const record=attrs.match(/data-lightbox-url="(\/sets\/\d+\/card\/\d+)"/)?.[1];
    const image=attrs.match(/href="(https:\/\/cdn\.artofpkm\.com\/[a-z0-9]+)"/)?.[1];
    if(!title||!record||!image)continue;
    const suffix=`, ${set.label}`,name=decode(title.endsWith(suffix)?title.slice(0,-suffix.length):title.split(',')[0]);
    rows.push({name,record,image});
  }
  return rows;
}
function parseSourceCards(set){
  const era=set.source.startsWith('PMCG')?'PMCG':'neo',dir=path.join(TCGDEX_DATA,era,set.source);
  return fs.readdirSync(dir).filter(file=>/^\d+\.ts$/.test(file)).map(file=>{
    const source=fs.readFileSync(path.join(dir,file),'utf8');
    const literal=source.match(/name:\s*\{[\s\S]*?ja:\s*("(?:[^"\\]|\\.)*")/)?.[1];
    const dex=source.match(/dexId:\s*\[\s*(\d+)\s*\]/)?.[1];
    return {id:`${set.source}-${file.slice(0,-3)}`,name:literal?JSON.parse(literal):'',dexId:dex?[Number(dex)]:[]};
  }).sort((a,b)=>a.id.localeCompare(b.id,undefined,{numeric:true}));
}
function emit(records,summary){
  const rows=records.map(r=>`    ${JSON.stringify([r.id,r.source,r.canonical,r.artSet,r.artCard,r.name,r.image])}`).join(',\n');
  return `'use strict';\n// Generated by scripts/generate-jp-artwork-v158.cjs; do not hand-edit.\n(()=>{\n  const rows=[\n${rows}\n  ];\n  const byId=new Map(rows.map(row=>[row[0],row]));\n  const setBySource=${JSON.stringify(Object.fromEntries(SETS.map(s=>[s.source,s.canonical])))};\n  const sourceSet=id=>String(id||'').slice(0,String(id||'').lastIndexOf('-'));\n  function resolve(card={}){\n    if((card.language||card.lang)!=='JP')return null;\n    const id=card.source_id||card.sourceId||card.catalogId||'';\n    const row=byId.get(id),source=sourceSet(id);\n    if(!row||row[1]!==source||setBySource[source]!==row[2])return null;\n    if(card.source_set_id&&card.source_set_id!==source)return null;\n    const canonical=window.JPCardmarketTwin?.canonicalSet?.(card);\n    if(canonical&&canonical!==row[2])return null;\n    if(card.set&&card.set!=='AUTO'&&card.set!==row[2])return null;\n    return {source_id:id,source_set_id:source,set:row[2],name:row[5],image:row[6],source:'artofpkm',sourceRecord:\`https://www.artofpkm.com/sets/\${row[3]}/card/\${row[4]}\`};\n  }\n  window.JPArtwork={resolve,coverage:${JSON.stringify(summary)},source:'https://www.artofpkm.com'};\n})();\n`;
}

(async()=>{
  if(!fs.existsSync(TCGDEX_DATA))throw new Error(`TCGdex data checkout not found: ${TCGDEX_DATA}`);
  const [pokemon,...artPages]=await Promise.all([
    get('https://pokeapi.co/api/v2/pokemon-species?limit=2000','json'),
    ...SETS.map(set=>get(`${ART}/sets/${set.art}`))
  ]);
  const species=new Map(pokemon.results.map(row=>[speciesKey(row.name),Number(row.url.match(/\/(\d+)\/$/)?.[1])]).filter(row=>row[1]));
  const records=[],summary=[];
  for(const [setIndex,set] of SETS.entries()){
    const artHtml=artPages[setIndex],details=parseSourceCards(set);
    const artCards=parseArtCards(artHtml,set);
    if(!artCards.length)throw new Error(`No artwork parsed for ${set.label}`);
    const artByDex=new Map();
    for(const card of artCards){
      const dex=species.get(speciesKey(card.name));
      if(!dex)continue;
      const list=artByDex.get(dex)||[];list.push(card);artByDex.set(dex,list);
    }
    let matched=0,ambiguous=0;
    for(const card of details){
      const dex=Array.isArray(card.dexId)&&card.dexId.length===1?card.dexId[0]:null;
      let choices=dex?artByDex.get(dex)||[]:[];
      if(!choices.length){
        const exact=artCards.filter(a=>key(a.name)===key(card.name));
        if(exact.length===1)choices=exact;
      }
      if(choices.length!==1){if(choices.length>1)ambiguous++;continue;}
      const art=choices[0],artCard=Number(art.record.split('/').pop());
      records.push({id:card.id,source:set.source,canonical:set.canonical,artSet:set.art,artCard,name:art.name,image:art.image});matched++;
    }
    summary.push({source_set_id:set.source,set:set.canonical,sourceCards:details.length,sourceArtwork:artCards.length,matched,ambiguous,missing:details.length-matched});
  }
  records.sort((a,b)=>a.id.localeCompare(b.id,undefined,{numeric:true}));
  if(new Set(records.map(r=>r.id)).size!==records.length)throw new Error('Duplicate source_id in manifest');
  const swinub=records.find(r=>r.id==='neo3-038');
  if(!swinub||swinub.name!=='Swinub'||swinub.artSet!==40||swinub.artCard!==13)throw new Error('Swinub Awakening Legends identity check failed');
  fs.writeFileSync('jp-artwork-v158.js',emit(records,summary));
  console.log(JSON.stringify({records:records.length,swinub,summary},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;});
