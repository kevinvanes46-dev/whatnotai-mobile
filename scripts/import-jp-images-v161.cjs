'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {ROOT,loadCatalog,readManifest,validateEntry,writeAtomic,generate}=require('./jp-image-tools-v161.cjs');
const hash=buffer=>crypto.createHash('sha256').update(buffer).digest('hex');
async function importImages(folder,{root=ROOT}={}){
  if(!folder||!fs.statSync(folder).isDirectory())throw Error('Usage: node scripts/import-jp-images-v161.cjs <folder>');
  let sharp;try{sharp=require('sharp');}catch{throw Error('Install the local image converter first: npm install --prefix scripts');}
  const lock=path.join(root,'.jp-image-import-v161.lock');
  const fd=fs.openSync(lock,'wx'); // Never run two writers against the same manifest.
  const created=[];
  try{
    const {catalog}=loadCatalog(root),manifest=readManifest(root);
    for(const [id,entry] of Object.entries(manifest))validateEntry(id,entry,catalog);
    const report={imported:[],duplicates:[],rejected:[]};
    const names=fs.readdirSync(folder).sort(),groups=new Map();
    for(const name of names){
      const match=/^((?:PMCG[1-6]|neo[1-4])-[0-9]{3})\.(jpg|jpeg|png|webp)$/i.exec(name);
      if(match){const group=groups.get(match[1])||[];group.push(name);groups.set(match[1],group);}
    }
    const knownHashes=new Map();
    for(const [id,entry] of Object.entries(manifest))for(const digest of [entry.sha256,entry.inputSha256].filter(Boolean))knownHashes.set(digest,id);
    fs.mkdirSync(path.join(root,'assets/cards/jp'),{recursive:true});
    for(const name of names){
      const match=/^((?:PMCG[1-6]|neo[1-4])-[0-9]{3})\.(jpg|jpeg|png|webp)$/i.exec(name),id=match?.[1];
      try{
        if(!id||!Object.hasOwn(catalog,id))throw Error('Unknown source_id, unsupported extension or non-exact filename');
        if(groups.get(id).length>1){report.duplicates.push({file:name,source_id:id,reason:'Multiple input files for this source_id; none imported'});continue;}
        const dest=path.join(root,`assets/cards/jp/${id}.webp`);
        if(Object.hasOwn(manifest,id)||fs.existsSync(dest)){report.duplicates.push({file:name,source_id:id,reason:'Existing image/manifest entry; not overwritten'});continue;}
        const input=path.join(folder,name),stat=fs.lstatSync(input);
        if(!stat.isFile()||stat.isSymbolicLink())throw Error('Only regular files are accepted');
        if(stat.size>30*1024*1024)throw Error('File exceeds 30 MiB limit');
        const buffer=fs.readFileSync(input),inputSha256=hash(buffer);
        const opts={failOn:'warning',limitInputPixels:40000000};
        const meta=await sharp(buffer,opts).metadata();
        const expected={jpg:'jpeg',jpeg:'jpeg',png:'png',webp:'webp'}[match[2].toLowerCase()];
        if(meta.format!==expected||!meta.width||!meta.height||(meta.pages||1)!==1)throw Error('Invalid, mismatched or animated image');
        // toBuffer fully decodes the source: checking only the header is insufficient.
        const {data,info}=await sharp(buffer,opts).rotate().resize({width:1200,height:1680,fit:'inside',withoutEnlargement:true}).webp({quality:90,effort:4}).toBuffer({resolveWithObject:true});
        const sha256=hash(data),duplicate=knownHashes.get(inputSha256)||knownHashes.get(sha256);
        if(duplicate){report.duplicates.push({file:name,source_id:id,reason:`Same image bytes as ${duplicate}; review identity manually`});continue;}
        fs.writeFileSync(dest,data,{flag:'wx'});created.push(dest);
        manifest[id]={src:`assets/cards/jp/${id}.webp`,...catalog[id],sha256,inputSha256,width:info.width,height:info.height};
        knownHashes.set(inputSha256,id);knownHashes.set(sha256,id);
        report.imported.push({file:name,source_id:id,src:manifest[id].src});
      }catch(error){report.rejected.push({file:name,source_id:id||null,reason:error.message});}
    }
    // All browser data and coverage are regenerated by the same command.
    report.coverage=generate(root,manifest);
    writeAtomic(path.join(root,'data/jp-image-import-report-v161.json'),JSON.stringify(report,null,2)+'\n');
    return report;
  }catch(error){
    // Preserve any image already referenced by a successfully published manifest.
    let published={};try{published=readManifest(root);}catch{}
    for(const file of created)if(!Object.values(published).some(entry=>path.join(root,entry.src)===file))fs.unlinkSync(file);
    throw error;
  }finally{fs.closeSync(fd);fs.unlinkSync(lock);}
}
if(require.main===module)importImages(process.argv[2]).then(report=>{
  console.log(JSON.stringify(report,null,2));if(report.rejected.length)process.exitCode=1;
}).catch(error=>{console.error(error.message);process.exitCode=1;});
module.exports={importImages};
